def generate_dataset():
    out_path = Path(__file__).resolve().parent / "data" / "hardcore_stress_sample.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    assert len(QUESTIONS) == 100, f"Expected 100 questions, got {len(QUESTIONS)}"

    categories = {}
    for q in QUESTIONS:
        cat = q["category"]
        categories[cat] = categories.get(cat, 0) + 1
        assert len(q["choices"]) == 4, f"Question {q['id']} choices != 4"
        assert q["answer"] in ("A", "B", "C", "D"), f"Question {q['id']} invalid answer {q['answer']}"
        assert len(q["question"]) > 10, f"Question {q['id']} question too short"

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(QUESTIONS, f, ensure_ascii=False, indent=2)

    print(f"Generated Hardcore Stress dataset at {out_path}")
    print(f"Total questions: {len(QUESTIONS)}")
    for cat, count in categories.items():
        print(f"  {cat}: {count}")


if __name__ == "__main__":
    generate_dataset()
